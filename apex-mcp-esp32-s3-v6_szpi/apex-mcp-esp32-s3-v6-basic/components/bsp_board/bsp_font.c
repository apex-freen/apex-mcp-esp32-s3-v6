void bsp_lcd_draw_text(int x, int y, const char *text, uint16_t color, uint16_t bg)
{
    if (text == NULL)
        return;

    int len = 0;
    while (text[len] && len < 40)
        len++;
    if (len == 0)
        return;

    int w = len * BSP_FONT_W; // 每字符 5 列 + 1 列间距
    // 整块文本缓冲（PSRAM），先填背景再写前景
    uint16_t *buf = (uint16_t *)heap_caps_malloc(w * BSP_FONT_H * 2, MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT);
    if (buf == NULL)
        return;

    for (int i = 0; i < w * BSP_FONT_H; i++)
        buf[i] = bg;

    for (int ci = 0; ci < len; ci++)
    {
        char c = text[ci];
        if (c < 32 || c > 126)
            c = '?';
        const uint8_t *glyph = s_font5x7[c - 32];

        for (int col = 0; col < 5; col++)
        {
            uint8_t bits = glyph[col];
            for (int row = 0; row < 7; row++)
            {
                if (bits & (1 << row))
                {
                    int px = ci * BSP_FONT_W + col;
                    buf[row * w + px] = color;
                }
            }
        }
    }

    bsp_lcd_draw_bitmap(x, y, x + w, y + BSP_FONT_H, buf);
    heap_caps_free(buf);
}
